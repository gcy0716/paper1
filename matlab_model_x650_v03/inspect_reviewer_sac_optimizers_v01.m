function inspect_reviewer_sac_optimizers_v01()
root=fileparts(mfilename('fullpath'));
for seed=[11 22 33]
    file=fullfile(root,'results','multiseed_v05_finetuned',sprintf('seed_%d',seed), ...
        sprintf('sac_seed_%d_finetuned_5episodes_v05.mat',seed));
    S=load(file,'agent'); o=S.agent.AgentOptions;
    fprintf('seed=%d sample=%.6g discount=%.6g buffer=%d batch=%d warm=%d ', ...
        seed,o.SampleTime,o.DiscountFactor,o.ExperienceBufferLength, ...
        o.MiniBatchSize,o.NumWarmStartSteps);
    fprintf('updates(actor,critic,target)=%d,%d,%d target_smooth=%.6g\n', ...
        o.PolicyUpdateFrequency,o.CriticUpdateFrequency, ...
        o.TargetUpdateFrequency,o.TargetSmoothFactor);
    fprintf('actor optimizer=%s rate=%.9g gradient_threshold=%.9g\n', ...
        string(o.ActorOptimizerOptions.Algorithm), ...
        o.ActorOptimizerOptions.LearnRate, ...
        o.ActorOptimizerOptions.GradientThreshold);
    for j=1:numel(o.CriticOptimizerOptions)
        c=o.CriticOptimizerOptions(j);
        fprintf('critic%d optimizer=%s rate=%.9g gradient_threshold=%.9g\n', ...
            j,string(c.Algorithm),c.LearnRate,c.GradientThreshold);
    end
    fprintf('entropy optimizer=%s rate=%.9g initial_weight=%.9g\n', ...
        string(o.EntropyWeightOptions.Algorithm), ...
        o.EntropyWeightOptions.LearnRate,o.EntropyWeightOptions.EntropyWeight);
end
end
