function [agent,stats]=train_sac_v03(runMode,seed)
% runMode="smoke" validates the pipeline; "full" is the planned study.
if nargin<1, runMode="smoke"; end
if nargin<2, seed=42; end
root=fileparts(mfilename('fullpath')); out=fullfile(root,'results');
rng(seed,'twister'); env=create_pemfc_rl_env_v03("train",seed);
obsInfo=getObservationInfo(env); actInfo=getActionInfo(env);
agentOpts=rlSACAgentOptions('SampleTime',0.5,'ExperienceBufferLength',2e5, ...
    'MiniBatchSize',128,'DiscountFactor',0.995);
agent=rlSACAgent(obsInfo,actInfo,agentOpts);
if string(runMode)=="smoke"
    trainOpts=rlTrainingOptions('MaxEpisodes',2,'MaxStepsPerEpisode',200, ...
        'Verbose',false,'Plots','none','StopTrainingCriteria','EpisodeCount', ...
        'StopTrainingValue',2);
elseif string(runMode)=="pilot"
    trainOpts=rlTrainingOptions('MaxEpisodes',5,'MaxStepsPerEpisode',600, ...
        'ScoreAveragingWindowLength',5,'Verbose',false,'Plots','none', ...
        'StopTrainingCriteria','EpisodeCount','StopTrainingValue',5);
elseif string(runMode)=="pretrain"
    checkpointDir=fullfile(out,'pretrain_checkpoints_v03');
    if ~exist(checkpointDir,'dir'), mkdir(checkpointDir); end
    trainOpts=rlTrainingOptions('MaxEpisodes',10,'MaxStepsPerEpisode',1200, ...
        'ScoreAveragingWindowLength',5,'Verbose',true,'Plots','none', ...
        'StopTrainingCriteria','EpisodeCount','StopTrainingValue',10, ...
        'SaveAgentCriteria','EpisodeCount','SaveAgentValue',5, ...
        'SaveAgentDirectory',checkpointDir);
else
    trainOpts=rlTrainingOptions('MaxEpisodes',500,'MaxStepsPerEpisode',2400, ...
        'ScoreAveragingWindowLength',20,'Verbose',true,'Plots','training-progress', ...
        'StopTrainingCriteria','AverageReward','StopTrainingValue',-500);
end
stats=train(agent,env,trainOpts);
save(fullfile(out,['sac_agent_' char(runMode) '_v03.mat']),'agent','stats','trainOpts','agentOpts','seed');
fprintf('SAC_TRAINING_%s_COMPLETE episodes=%d\n',upper(char(runMode)),numel(stats.EpisodeIndex));
end
